"""Train a fitted-Q NumPy MLP for row-mask 000040/000056 fusion.

The input dataset contains exact Bellman Q labels generated by
``export_transition_q_value_dataset.py``. This script fits Q(t,a,b,c) and
decodes a policy by greedily taking the lowest predicted Q from each
second-order state.
"""

